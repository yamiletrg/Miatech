SELECT SCARDN,SAUTHOC,SVFOP,SDATE,SCURRENCY,MONEDAPAGO,IMPORTEPAG,SAGENT,MERCHNC  FROM PRAXISMP.MPF101



SELECT 
  	A.IDCONT,A.SCARDN, A.SAUTHOC, A.SVFOP, A.SDATE, A.SCURRENCY, A.MONEDAPAGO, A.IMPORTEPAG, A.SAGENT, A.MERCHNC,
    B.DATEC, B.TRANC,B.CODPRO
FROM PRAXISMP.MPF101 A
INNER JOIN PRAXISMP.MPF100 B
       ON A.IDCONT = B.IDCONT
--WHERE A.IDCONT = '202REGCM12509250916191311';
       
       
       
       
       SELECT A.BANDOC,
       A.DATEC,
       A.TRANC,
       A.SFVOP,
       B.TKT
FROM (
    SELECT BANDOC,
           DATEC,
           TRANC,
           SUM(SVFOP) AS SFVOP
    FROM PRAXISMP.MPF101
    WHERE IDCONT = '202REGCM12509250916191311'
      AND TDOC = 'S'
      AND STVAL = '1'
    GROUP BY BANDOC, DATEC, TRANC
) A
INNER JOIN (
    SELECT BANDOC,
           DATEC,
           TRANC,
           LISTAGG(CCIA || FORMA || SERIE, '-') AS TKT
    FROM PRAXISMP.MPF100
    WHERE IDCONT = '202REGCM12509250916191311'
    GROUP BY BANDOC, DATEC, TRANC
) B
ON A.BANDOC = B.BANDOC
   AND A.DATEC = B.DATEC
   AND A.TRANC = B.TRANC
ORDER BY A.BANDOC, A.DATEC, A.TRANC;









