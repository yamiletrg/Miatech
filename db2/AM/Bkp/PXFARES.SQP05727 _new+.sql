CREATE OR REPLACE PROCEDURE PXFARES.SQP05727 
(
    IN VL_CCUST  VARCHAR(3), 
    IN VL_FECINI VARCHAR(8), 
    IN VL_FECFIN VARCHAR(8), 
    IN VL_OPCION VARCHAR(2)
)
    RESULT SETS 1
    LANGUAGE SQL
    SPECIFIC PXFARES.SQP05727
BEGIN

-- ===================================================
-- Cursor 1: CargoCP.py - Opción 1
-- ===================================================
DECLARE C1 CURSOR FOR
WITH FILTRAR_TICKET AS (
      SELECT A1672CCUST,A1672CIA, A1672FORMA, A1672SERIE, A1672SEQ, A1672FUENT, A1672CANAL, 
             A1672ITIN, A1672FVENT, A1672TIPOF, A1672PNRSP, A1672PAIVT, A1672CTYEM
      FROM PXSAUDIT.A1672 
      WHERE A1672CCUST = VL_CCUST 
        AND A1672FPROC BETWEEN VL_FECINI AND VL_FECFIN 
        AND A1672TRNCU = 'EXCH' 
        AND A1672STS0 <> '0'
),
FILTRO_A1673 AS (
      SELECT A1673CCUST, A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673MORIG, A1673TXORI, A1673CDTAX
      FROM PXSAUDIT.A1673 A1673
      WHERE A1673CCUST = VL_CCUST
        AND EXISTS (
          SELECT 1 
          FROM FILTRAR_TICKET FT 
          WHERE FT.A1672CCUST = A1673.A1673CCUST
            AND FT.A1672CIA   = A1673.A1673CIA 
            AND FT.A1672FORMA = A1673.A1673FORMA 
            AND FT.A1672SERIE = A1673.A1673SERIE 
            AND FT.A1672SEQ   = A1673.A1673SEQ
        )
        AND ( (LENGTH(TRIM(A1673CDTAX)) = 3 AND A1673CDTAX NOT IN ('F11','F31','F71','F72')) 
               OR A1673CDTAX = 'CP')
),
MORIGS AS (
      SELECT A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673MORIG,
             ROW_NUMBER() OVER (PARTITION BY A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ ORDER BY A1673MORIG) AS rn_morig
      FROM FILTRO_A1673
),
TXS AS (
      SELECT A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673TXORI, A1673CDTAX,
             ROW_NUMBER() OVER (PARTITION BY A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ ORDER BY A1673TXORI, A1673CDTAX) AS rn_tx
      FROM FILTRO_A1673
)
SELECT 
      FT.A1672CCUST,
      FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE AS TICKET,
      FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,FT.A1672CTYEM,
      FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP,
      CASE WHEN MAX(CASE WHEN M.rn_morig = 1 THEN M.A1673MORIG END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 1 THEN M.A1673MORIG END))) END AS MORIG_1,
      CASE WHEN MAX(CASE WHEN M.rn_morig = 2 THEN M.A1673MORIG END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 2 THEN M.A1673MORIG END))) END AS MORIG_2,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673TXORI END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673TXORI END))) END AS TXORI_1,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673CDTAX END) IS NULL THEN '' ELSE TRIM(MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673CDTAX END)) END AS CDTAX_1,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673TXORI END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673TXORI END))) END AS TXORI_2,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673CDTAX END) IS NULL THEN '' ELSE TRIM(MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673CDTAX END)) END AS CDTAX_2
FROM FILTRAR_TICKET FT
LEFT JOIN MORIGS M 
       ON FT.A1672CCUST = M.A1673CCUST
      AND FT.A1672CIA   = M.A1673CIA 
      AND FT.A1672FORMA = M.A1673FORMA 
      AND FT.A1672SERIE = M.A1673SERIE 
      AND FT.A1672SEQ   = M.A1673SEQ
LEFT JOIN TXS TX 
       ON FT.A1672CCUST = TX.A1673CCUST
      AND FT.A1672CIA   = TX.A1673CIA 
      AND FT.A1672FORMA = TX.A1673FORMA 
      AND FT.A1672SERIE = TX.A1673SERIE 
      AND FT.A1672SEQ   = TX.A1673SEQ
GROUP BY FT.A1672CCUST,FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE,
         FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,
         FT.A1672CTYEM,FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP;

-- ===================================================
-- Cursor 2: versión A1532 (equivalente a CargoCP_NEW.py Opción 02)
-- ===================================================
DECLARE C2 CURSOR WITH RETURN FOR
WITH FILTRAR_TICKET AS (
    SELECT A1672CCUST, A1672CIA, A1672FORMA, A1672SERIE, A1672SEQ,
           A1672FUENT, A1672CANAL, A1672ITIN, A1672FVENT,
           A1672TIPOF, A1672PNRSP, A1672PAIVT, A1672CTYEM
    FROM PXSAUDIT.A1672
    WHERE A1672CCUST = VL_CCUST
      AND A1672FPROC BETWEEN VL_FECINI AND VL_FECFIN
      AND A1672TRNCU = 'EXCH'
      AND A1672STS0 <> '0'
),
MORIGS AS (
    SELECT A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ,
           MAX(CASE WHEN RN=1 THEN A1532MTAX END) AS MORIG_1,
           MAX(CASE WHEN RN=2 THEN A1532MTAX END) AS MORIG_2
    FROM (
        SELECT A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ, A1532MTAX,
               ROW_NUMBER() OVER (
                   PARTITION BY A1532CCUST,A1532CIA,A1532FORMA,A1532SERIE,A1532SEQ
                   ORDER BY A1532MTAX
               ) AS RN
        FROM PRAXIS.A1532 A
        WHERE ((LENGTH(TRIM(A1532CTAX)) = 3 AND A1532CTAX NOT IN ('F11','F31','F71','F72'))
               OR A1532CTAX IN ('CP','IVA'))
          AND EXISTS (
              SELECT 1 FROM FILTRAR_TICKET FT
              WHERE FT.A1672CCUST = A.A1532CCUST
                AND FT.A1672CIA   = A.A1532CIA
                AND FT.A1672FORMA = A.A1532FORMA
                AND FT.A1672SERIE = A.A1532SERIE
                AND FT.A1672SEQ   = A.A1532SEQ
          )
    ) SUB
    GROUP BY A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ
),
TXS AS (
    SELECT A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ,
           SUM(CASE WHEN A1532CTAX='IVA' THEN A1532VTAX ELSE 0 END) AS MONTO_1,
           SUM(CASE WHEN A1532CTAX='CP'  THEN A1532VTAX ELSE 0 END) AS MONTO_2,
           MAX(CASE WHEN A1532CTAX='IVA' THEN A1532MTAX END) AS MONEDA_1,
           MAX(CASE WHEN A1532CTAX='CP'  THEN A1532MTAX END) AS MONEDA_2
    FROM PRAXIS.A1532 A
    WHERE ((LENGTH(TRIM(A1532CTAX)) = 3 AND A1532CTAX NOT IN ('F11','F31','F71','F72'))
           OR A1532CTAX IN ('CP','IVA'))
      AND EXISTS (
          SELECT 1 FROM FILTRAR_TICKET FT
          WHERE FT.A1672CCUST = A.A1532CCUST
            AND FT.A1672CIA   = A.A1532CIA
            AND FT.A1672FORMA = A.A1532FORMA
            AND FT.A1672SERIE = A.A1532SERIE
            AND FT.A1672SEQ   = A.A1532SEQ
      )
    GROUP BY A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ
)
SELECT
    FT.A1672CCUST,
    FT.A1672CIA || FT.A1672FORMA || FT.A1672SERIE AS TICKET,
    FT.A1672SEQ,
    FT.A1672FUENT,
    FT.A1672CANAL,
    FT.A1672PAIVT,
    FT.A1672CTYEM,
    FT.A1672ITIN,
    FT.A1672FVENT,
    FT.A1672TIPOF,
    FT.A1672PNRSP,
    COALESCE(M.MORIG_1,'') AS MORIG_1,
    COALESCE(M.MORIG_2,'') AS MORIG_2,
    COALESCE(T.MONEDA_1,'') AS MONEDA_1,
    COALESCE(T.MONEDA_2,'') AS MONEDA_2,
    COALESCE(T.MONTO_1,0) AS MONTO_1,
    CASE WHEN COALESCE(T.MONTO_1,0) > 0 THEN 'IVA' ELSE '' END AS TAX_1,
    COALESCE(T.MONTO_2,0) AS MONTO_2,
    CASE WHEN COALESCE(T.MONTO_2,0) > 0 THEN 'CP' ELSE '' END AS TAX_2,
    'CON CP' AS FLAG_CP
FROM FILTRAR_TICKET FT
LEFT JOIN MORIGS M
  ON FT.A1672CCUST = M.A1532CCUST
 AND FT.A1672CIA   = M.A1532CIA
 AND FT.A1672FORMA = M.A1532FORMA
 AND FT.A1672SERIE = M.A1532SERIE
 AND FT.A1672SEQ   = M.A1532SEQ
LEFT JOIN TXS T
  ON FT.A1672CCUST = T.A1532CCUST
 AND FT.A1672CIA   = T.A1532CIA
 AND FT.A1672FORMA = T.A1532FORMA
 AND FT.A1672SERIE = T.A1532SERIE
 AND FT.A1672SEQ   = T.A1532SEQ
;


-- ===================================================
-- Cursor 3: (equivalente a Cargo_F71F72 Opción 03)
-- ===================================================
DECLARE C3 CURSOR FOR
WITH FILTRAR_TICKET AS (
	SELECT A1672CCUST , A1672CIA , A1672FORMA , A1672SERIE , A1672SEQ ,
	A1672FUENT , A1672CANAL , A1672ITIN , A1672FVENT , A1672TIPOF ,
	A1672CNX1 , A1672IATAV , A1672PAIVT , A1672CTYEM
	FROM PXSAUDIT . A1672
	WHERE A1672CCUST = VL_CCUST
		AND A1672FPROC BETWEEN VL_FECINI AND VL_FECFIN
		AND A1672FUENT = 'BSP'
		AND A1672TRNCU = 'EXCH'
		AND A1672STS0 <> '0'
) ,
F71 AS (
	SELECT A1673CCUST , A1673CIA , A1673FORMA , A1673SERIE , A1673SEQ ,
	A1673MORIG AS MONEDA_F71 , A1673TXORI AS MONTO_F71
	FROM PXSAUDIT . A1673
	WHERE A1673CCUST = VL_CCUST
		AND A1673CDTAX = 'F71'
) ,
F72 AS (
	SELECT A1673CCUST , A1673CIA , A1673FORMA , A1673SERIE , A1673SEQ ,
	A1673MORIG AS MONEDA_F72 , A1673TXORI AS MONTO_F72
	FROM PXSAUDIT . A1673
	WHERE A1673CCUST = VL_CCUST
		AND A1673CDTAX = 'F72'
)
SELECT
	FT . A1672CCUST ,
	FT . A1672CIA || FT . A1672FORMA || FT . A1672SERIE AS TICKET ,
	FT . A1672SEQ ,
	FT . A1672IATAV , -- IATA
	FT . A1672FUENT , -- Fuente
	FT . A1672CANAL , -- Canal
	COALESCE ( F71 . MONEDA_F71 , '' ) AS MONEDA1 ,
	COALESCE ( F72 . MONEDA_F72 , '' ) AS MONEDA2 ,
	COALESCE ( F71 . MONTO_F71 , 0 ) AS MONTO1 ,
	COALESCE ( F72 . MONTO_F72 , 0 ) AS MONTO2 ,
	FT . A1672PAIVT , -- País
	FT . A1672CTYEM , -- TKTEMD
	CASE
		WHEN F71 . MONTO_F71 IS NOT NULL OR F72 . MONTO_F72 IS NOT NULL
	THEN 'CON F71 O F72'
		ELSE 'SIN F71 O F72'
	END AS ESTADO
	FROM FILTRAR_TICKET FT
	LEFT JOIN F71
		ON FT . A1672CCUST = F71 . A1673CCUST
		AND FT . A1672CIA = F71 . A1673CIA
		AND FT . A1672FORMA = F71 . A1673FORMA
		AND FT . A1672SERIE = F71 . A1673SERIE
		AND FT . A1672SEQ = F71 . A1673SEQ
	LEFT JOIN F72
		ON FT . A1672CCUST = F72 . A1673CCUST
		AND FT . A1672CIA = F72 . A1673CIA
		AND FT . A1672FORMA = F72 . A1673FORMA
		AND FT . A1672SERIE = F72 . A1673SERIE
		AND FT . A1672SEQ = F72 . A1673SEQ ;

