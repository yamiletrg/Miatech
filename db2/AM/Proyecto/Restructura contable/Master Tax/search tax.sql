CREATE OR REPLACE PROCEDURE PRAXIS.SQP04484 ( IN IN_A1741PAIS VARCHAR(2),
                                   IN IN_A1741MONED VARCHAR(3),
                                   IN IN_A1741CODE VARCHAR(3),
                                   IN IN_A1741TIPO CHAR(1),
                                   IN IN_A1741CTA VARCHAR(6),
                                   IN IN_A1741SCTA VARCHAR(5),
                                   INOUT IO_PAGNUM INTEGER,
                                   INOUT IO_PAGROW INTEGER,
                                   INOUT IO_TOTPAG INTEGER,
                                   INOUT IO_TOTROW INTEGER,
                                   IN IN_A1741CTRL CHAR(1) )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.SQP04484

BEGIN

DECLARE PAGROWINIT INT ;
DECLARE SQLPAG01 VARCHAR ( 2100 ) ;
DECLARE V_VCSQL VARCHAR ( 2000 ) ;
DECLARE CURQRY01 CURSOR FOR STMTQRY01 ;
	
SET V_VCSQL = 'SELECT COUNT(0) FROM (SELECT A1741CCUST, A1741TIPO, A1741PAIS,
A1741CODE,A1741MONED,A1741CONCE,A1741TPTAX,A1741CTRL,
A1741CIA,A1741UNIDA,A1741CECOS,A1741UBICA,A1741CTA,A1741SCTA,
A1741EQUI,A1741ICIA,A1741FINI,A1741FFIN,A1741REGIS,A1741FREGI,
A1741HREGI,A1741REGVI,A1741FREVI,A1741HREVI,
CASE WHEN A1741INTNU = ''Y'' THEN ''YES'' ELSE ''NO'' END AS A1741INTNU  
FROM PRAXIS.A1741 WHERE 
(A1741PAIS = ''' CONCAT IN_A1741PAIS CONCAT ''' OR ''' CONCAT IN_A1741PAIS
CONCAT ''' = '''') AND
(A1741TIPO = ''' CONCAT IN_A1741TIPO CONCAT ''' OR ''' CONCAT IN_A1741TIPO
CONCAT ''' = '''') AND
(A1741CODE = ''' CONCAT IN_A1741CODE CONCAT ''' OR ''' CONCAT IN_A1741CODE
CONCAT ''' = '''') AND 
(A1741MONED = ''' CONCAT IN_A1741MONED CONCAT ''' OR ''' CONCAT IN_A1741MONED
CONCAT ''' = '''') AND 
(A1741CTA = ''' CONCAT IN_A1741CTA CONCAT ''' OR ''' CONCAT IN_A1741CTA
CONCAT ''' = '''') AND 
(A1741SCTA = ''' CONCAT IN_A1741SCTA CONCAT ''' OR ''' CONCAT IN_A1741SCTA
CONCAT ''' = '''') AND
(A1741CTRL = ''' CONCAT IN_A1741CTRL CONCAT ''' OR ''' CONCAT IN_A1741CTRL
CONCAT ''' = '''')
)T ' ;



PREPARE STMTQRY01 FROM V_VCSQL ;
OPEN CURQRY01 ;
FETCH CURQRY01 INTO IO_TOTROW ;
CLOSE CURQRY01 ;

SET V_VCSQL = ' SELECT ROW_NUMBER() OVER() AS NO, T.* FROM 
(SELECT A1741CCUST,A1741TIPO,
A1741PAIS,A1741CODE,A1741MONED,A1741CONCE,TRIM(A1741TPTAX) AS A1741TPTAX,
TRIM(A1741CTRL) AS A1741CTRL,
A1741CIA,A1741UNIDA,A1741CECOS,A1741UBICA,A1741CTA,A1741SCTA,
A1741EQUI,A1741ICIA,A1741FINI,A1741FFIN,A1741REGIS,A1741FREGI,
A1741HREGI,A1741REGVI,A1741FREVI,A1741HREVI,
CASE WHEN A1741INTNU = ''Y'' THEN ''YES'' ELSE ''NO'' END AS A1741INTNU  
FROM PRAXIS.A1741 WHERE 
(A1741PAIS = ''' CONCAT IN_A1741PAIS CONCAT ''' OR ''' CONCAT IN_A1741PAIS
CONCAT ''' = '''') AND
(A1741TIPO = ''' CONCAT IN_A1741TIPO CONCAT ''' OR ''' CONCAT IN_A1741TIPO
CONCAT ''' = '''') AND
(A1741CODE = ''' CONCAT IN_A1741CODE CONCAT ''' OR ''' CONCAT IN_A1741CODE
CONCAT ''' = '''') AND 
(A1741MONED = ''' CONCAT IN_A1741MONED CONCAT ''' OR ''' CONCAT IN_A1741MONED
CONCAT ''' = '''') AND 
(A1741CTA = ''' CONCAT IN_A1741CTA CONCAT ''' OR ''' CONCAT IN_A1741CTA
CONCAT ''' = '''') AND 
(A1741SCTA = ''' CONCAT IN_A1741SCTA CONCAT ''' OR ''' CONCAT IN_A1741SCTA
CONCAT ''' = '''') AND
(A1741CTRL = ''' CONCAT IN_A1741CTRL CONCAT ''' OR ''' CONCAT IN_A1741CTRL
CONCAT ''' = '''')
)T ' ;

SET SQLPAG01 = 'SELECT * FROM (' CONCAT V_VCSQL CONCAT ') AS RS 
				WHERE RS.NO >= ' CONCAT IO_PAGNUM ;
IF IO_PAGROW > 0 THEN
	SET SQLPAG01 = SQLPAG01 CONCAT ' FETCH FIRST ' CONCAT
IO_PAGROW CONCAT ' ROWS ONLY' ;
END IF ;

PREPARE STMTQRY01 FROM SQLPAG01 ;
OPEN CURQRY01 ;

END