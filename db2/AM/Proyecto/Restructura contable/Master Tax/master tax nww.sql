CREATE OR REPLACE PROCEDURE PRAXIS.SQP04485 ( IN IN_ACTION CHAR(1),
                                   IN IN_A1741CCUST VARCHAR(3),
                                   IN IN_A1741TIPO CHAR(1),
                                   IN IN_A1741PAIS VARCHAR(2),
                                   IN IN_A1741CODE VARCHAR(3),
                                   IN IN_A1741MONED VARCHAR(3),
                                   IN IN_A1741CONCE VARCHAR(50),
                                   IN IN_A1741CIA VARCHAR(2),
                                   IN IN_A1741UNIDA VARCHAR(2), -- READ ONLY
                                   IN IN_A1741CECOS VARCHAR(7), -- REESTRUCTURACION CONTABLE
                                   IN IN_A1741UBICA VARCHAR(4),
                                   IN IN_A1741CTA VARCHAR(6), -- REESTRUCTURACION CONTABLE 
                                   IN IN_A1741SCTA VARCHAR(5), -- REESTRUCTURACION CONTABLE (5 a 4 )
                                   IN IN_A1741EQUI VARCHAR(4),
                                   IN IN_A1741ICIA VARCHAR(2),
                                   IN IN_A1741FINI VARCHAR(8),
                                   IN IN_A1741FFIN VARCHAR(8),
                                   IN IN_USR VARCHAR(10),
                                   IN IN_FEC VARCHAR(8),
                                   IN IN_HOR VARCHAR(6),
                                   IN IN_A1741PAIS_OLD VARCHAR(2),
                                   IN IN_A1741CODE_OLD VARCHAR(3),
                                   IN IN_A1741TIPO_OLD CHAR(1),
                                   IN IN_A1741CTRL VARCHAR(1),
                                   IN IN_A1741TPTAX VARCHAR(2),
                                   IN IN_A1741FINI_OLD VARCHAR(8),
                                   IN IN_A1741FFIN_OLD VARCHAR(8),
                                   IN IN_A1741INTNU CHAR(1) )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.SQP04485

BEGIN
DECLARE VL_SQLCODE INTEGER DEFAULT 0 ;
DECLARE SQLCODE INTEGER DEFAULT 0 ;
DECLARE VL_MESSAGE VARCHAR ( 100 ) DEFAULT NULL ;
DECLARE CURQRY CURSOR FOR SELECT VL_MESSAGE AS VMESSAGE , VL_SQLCODE
AS VSQLCODE FROM ( VALUES ( '' , 0 ) ) AS TBL ;
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
SET VL_SQLCODE = REPLACE ( SQLCODE , '-' , '' ) ;

IF TRIM ( IN_A1741FFIN_OLD ) = '' THEN
SET IN_A1741FFIN_OLD = '99999999' ;
END IF ;

IF IN_ACTION = 'I' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1741
WHERE A1741CODE = IN_A1741CODE AND A1741TIPO = IN_A1741TIPO
AND A1741FINI = IN_A1741FINI_OLD AND A1741FFIN = IN_A1741FFIN_OLD ) THEN

INSERT INTO PRAXIS . A1741
( A1741CCUST , A1741TIPO , A1741PAIS , A1741CODE ,
A1741MONED , A1741CONCE , A1741CIA , A1741UNIDA , A1741CECOS ,
A1741UBICA , A1741CTA , A1741SCTA , A1741EQUI , A1741ICIA , A1741FINI ,
A1741FFIN , A1741REGIS , A1741FREGI , A1741HREGI , A1741REGVI ,
A1741FREVI , A1741HREVI , A1741CTRL , A1741TPTAX , A1741INTNU )
VALUES ( IN_A1741CCUST ,
IN_A1741TIPO ,
IN_A1741PAIS ,
IN_A1741CODE ,
IN_A1741MONED ,
IN_A1741CONCE ,
IN_A1741CIA ,
IN_A1741UNIDA ,
IN_A1741CECOS ,
IN_A1741UBICA ,
IN_A1741CTA ,
IN_A1741SCTA ,
IN_A1741EQUI ,
IN_A1741ICIA ,
IN_A1741FINI ,
IN_A1741FFIN ,
IN_USR ,
IN_FEC ,
IN_HOR ,
'' ,
'' ,
'' ,
IN_A1741CTRL ,
IN_A1741TPTAX ,
IN_A1741INTNU ) ;
SET VL_MESSAGE = 'RECORD INSERTED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'U' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1741
WHERE ( A1741CODE = IN_A1741CODE AND A1741TIPO = IN_A1741TIPO
AND A1741FINI = IN_A1741FINI AND A1741FFIN = IN_A1741FFIN )
AND ( IN_A1741CODE <> IN_A1741CODE_OLD
OR IN_A1741TIPO <> IN_A1741TIPO_OLD
OR IN_A1741FINI <> IN_A1741FINI_OLD
OR IN_A1741FFIN <> IN_A1741FFIN_OLD ) ) THEN

UPDATE PRAXIS . A1741
SET ( A1741CCUST , A1741TIPO , A1741PAIS , A1741CODE , A1741MONED ,
A1741CONCE , A1741CIA , A1741UNIDA , A1741CECOS , A1741UBICA ,
A1741CTA , A1741SCTA ,
A1741EQUI , A1741ICIA , A1741FINI , A1741FFIN ,
A1741REGVI , A1741FREVI , A1741HREVI , A1741CTRL , A1741TPTAX , A1741INTNU )
= ( IN_A1741CCUST ,
IN_A1741TIPO ,
IN_A1741PAIS ,
IN_A1741CODE ,
IN_A1741MONED ,
IN_A1741CONCE ,
IN_A1741CIA ,
IN_A1741UNIDA ,
IN_A1741CECOS ,
IN_A1741UBICA ,
IN_A1741CTA ,
IN_A1741SCTA ,
IN_A1741EQUI ,
IN_A1741ICIA ,
IN_A1741FINI ,
IN_A1741FFIN ,
IN_USR ,
IN_FEC ,
IN_HOR ,
IN_A1741CTRL ,
IN_A1741TPTAX ,
IN_A1741INTNU )
WHERE A1741CCUST = IN_A1741CCUST AND

A1741CODE = IN_A1741CODE_OLD AND
A1741TIPO = IN_A1741TIPO_OLD AND
A1741FINI = IN_A1741FINI_OLD AND
A1741FFIN = IN_A1741FFIN_OLD ;
SET VL_MESSAGE = 'RECORD UPDATED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'D' THEN
DELETE FROM PRAXIS . A1741
WHERE A1741CCUST = IN_A1741CCUST AND
A1741PAIS = IN_A1741PAIS_OLD AND
A1741CODE = IN_A1741CODE_OLD AND
A1741TIPO = IN_A1741TIPO_OLD AND
A1741FINI = IN_A1741FINI_OLD AND
A1741FFIN = IN_A1741FFIN_OLD ;
SET VL_MESSAGE = 'RECORD REMOVED' ;
OPEN CURQRY ;
END IF ;


IF ( VL_SQLCODE <> 0 ) THEN		
	SELECT DB_MESSAGE INTO VL_MESSAGE FROM PRAXIS . INF054
WHERE DB_SQLCODE = VL_SQLCODE ;
	IF VL_MESSAGE IS NULL THEN
		SET VL_MESSAGE = 'AN UNEXPECTED ERROR OCCURRED, CODE '
CONCAT VL_SQLCODE ;
	END IF ;
ELSE
	SET VL_MESSAGE = 'OPERATION WAS SUCCESSFUL' ;			
END IF ;


OPEN CURQRY ;

END