CREATE OR REPLACE PROCEDURE PRAXIS.PX160S01A1819 ( IN IN_A1819CCUST CHAR(3),
                                        IN IN_A1819TIPO CHAR(2),
                                        IN IN_A1819CLIEN VARCHAR(15),
                                        IN IN_A1819MODO CHAR(2),
                                        IN IN_A1819TACC VARCHAR(20),
                                        IN IN_A1819NATU CHAR(3),
                                        IN IN_A1819CTA CHAR(6),
                                        IN IN_A1819SCTA VARCHAR(5),
                                        INOUT IO_PAGNUM INTEGER,
                                        INOUT IO_PAGROW INTEGER,
                                        INOUT IO_TOTPAG INTEGER,
                                        INOUT IO_TOTROW INTEGER )
	RESULT SETS 2
	LANGUAGE SQL
	SPECIFIC PRAXIS.PX160S01A1819

BEGIN

DECLARE CURQRY_COUNT CURSOR FOR

SELECT COUNT ( 0 ) FROM
(
SELECT * FROM PRAXIS . A1819
WHERE A1819CCUST = IN_A1819CCUST
AND ( A1819TIPO = IN_A1819TIPO OR IN_A1819TIPO = '' )
AND ( A1819CLIEN = IN_A1819CLIEN OR IN_A1819CLIEN = '' )
AND ( A1819MODO = IN_A1819MODO OR IN_A1819MODO = '' )
AND ( A1819TACC LIKE '%' CONCAT IN_A1819TACC CONCAT '%'
OR IN_A1819TACC = '' )
AND ( A1819NATU = IN_A1819NATU OR IN_A1819NATU = '' )
AND ( A1819CTA = IN_A1819CTA OR IN_A1819CTA = '' )
AND ( A1819SCTA = IN_A1819SCTA OR IN_A1819SCTA = '' )
) AS T ;

DECLARE CURQRY01 CURSOR FOR
SELECT * FROM (
SELECT ROW_NUMBER ( ) OVER ( ) AS RN , T . * FROM
(
SELECT A1819CCUST , A1819TACC , A1819NATU , A1819DESCR , A1819CLIEN ,
A1819DIREC , A1819TIPO , A1819MODO , A1819CIA , A1819UNID , A1819CECO ,
A1819UBI , A1819CTA , A1819SCTA , A1819EQUI , A1819ICIA , A1819FINI ,
A1819FFIN , A1819REGIS , A1819FREGI , A1819HREGI , A1819REGVI ,
A1819FREVI , A1819HREVI
FROM PRAXIS . A1819
WHERE A1819CCUST = IN_A1819CCUST
AND ( A1819TIPO = IN_A1819TIPO OR IN_A1819TIPO = '' )
AND ( A1819CLIEN = IN_A1819CLIEN OR IN_A1819CLIEN = '' )
AND ( A1819MODO = IN_A1819MODO OR IN_A1819MODO = '' )
AND ( A1819TACC LIKE '%' CONCAT IN_A1819TACC CONCAT '%'
OR IN_A1819TACC = '' )
AND ( A1819NATU = IN_A1819NATU OR IN_A1819NATU = '' )
AND ( A1819CTA = IN_A1819CTA OR IN_A1819CTA = '' )
AND ( A1819SCTA = IN_A1819SCTA OR IN_A1819SCTA = '' )
) AS T
) AS RS
WHERE RS . RN >= IO_PAGNUM
AND ( ( IO_PAGNUM - RS . RN + IO_PAGROW ) > 0 OR IO_PAGROW = - 1 )
ORDER BY A1819TIPO ;

OPEN CURQRY01 ;
OPEN CURQRY_COUNT ;

FETCH CURQRY_COUNT INTO IO_TOTROW ;

END