CREATE PROCEDURE PRAXIS.PX160S02A1819 ( IN IN_ACTION CHAR(1),
                                        IN IN_A1819CCUST CHAR(3),
                                        IN IN_A1819TACC VARCHAR(20),
                                        IN IN_A1819NATU VARCHAR(3),
                                        IN IN_A1819DESCR VARCHAR(60),
                                        IN IN_A1819CLIEN VARCHAR(15),
                                        IN IN_A1819DIREC VARCHAR(15),
                                        IN IN_A1819TIPO CHAR(2),
                                        IN IN_A1819MODO CHAR(2),
                                        IN IN_A1819CIA VARCHAR(2),
                                        IN IN_A1819UNID VARCHAR(2), -- READ ONLY
                                        --IN N_A1819CECO VARCHAR(6),
                                        IN IN_A1819CECO VARCHAR(7),  -- REESTRUCTURACION CONTABLE 
                                        IN IN_A1819UBI VARCHAR(4),
                                        --IN IN_A1819CTA VARCHAR(4),
                                        IN IN_A1819CTA VARCHAR(6), -- REESTRUCTURACION CONTABLE 
                                        --IN IN_A1819SCTA VARCHAR(5),
                                        IN IN_A1819SCTA VARCHAR(5),-- REESTRUCTURACION CONTABLE 
                                        IN IN_A1819EQUI VARCHAR(4),
                                        IN IN_A1819ICIA VARCHAR(2),
                                        IN IN_A1819FINI VARCHAR(8),
                                        IN IN_A1819FFIN VARCHAR(8),
                                        IN IN_USR VARCHAR(10),
                                        IN IN_FEC VARCHAR(8),
                                        IN IN_HOR VARCHAR(6),
                                        IN IN_A1819TACC_OLD VARCHAR(50) )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.PX160S02A1819

BEGIN
DECLARE VL_SQLCODE INTEGER DEFAULT 0 ;
DECLARE SQLCODE INTEGER DEFAULT 0 ;
DECLARE VL_MESSAGE VARCHAR ( 100 ) DEFAULT NULL ;
DECLARE CURQRY CURSOR FOR SELECT VL_MESSAGE AS VMESSAGE , VL_SQLCODE
AS VSQLCODE FROM ( VALUES ( '' , 0 ) ) AS TBL ;
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
SET VL_SQLCODE = REPLACE ( SQLCODE , '-' , '' ) ;


IF IN_ACTION = 'I' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1819
WHERE A1819CCUST = IN_A1819CCUST AND A1819TACC = IN_A1819TACC ) THEN

INSERT INTO PRAXIS . A1819
( A1819CCUST , A1819TACC , A1819NATU , A1819DESCR , A1819CLIEN ,
A1819DIREC , A1819TIPO , A1819MODO , A1819CIA , A1819UNID , A1819CECO ,
A1819UBI , A1819CTA , A1819SCTA , A1819EQUI , A1819ICIA , A1819FINI ,
A1819FFIN , A1819REGIS , A1819FREGI , A1819HREGI , A1819REGVI , A1819FREVI ,
A1819HREVI )
VALUES ( IN_A1819CCUST ,
IN_A1819TACC ,
IN_A1819NATU ,
IN_A1819DESCR ,
IN_A1819CLIEN ,
IN_A1819DIREC ,
IN_A1819TIPO ,
IN_A1819MODO ,
IN_A1819CIA ,
IN_A1819UNID ,
IN_A1819CECO ,
IN_A1819UBI ,
IN_A1819CTA ,
IN_A1819SCTA ,
IN_A1819EQUI ,
IN_A1819ICIA ,
IN_A1819FINI ,
IN_A1819FFIN ,
IN_USR ,
IN_FEC ,
IN_HOR ,
'' ,
'' ,
'' ) ;
SET VL_MESSAGE = 'RECORD INSERTED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'U' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1819
WHERE ( A1819CCUST = IN_A1819CCUST AND A1819TACC = IN_A1819TACC )
AND ( IN_A1819TACC <> IN_A1819TACC_OLD ) ) THEN

UPDATE PRAXIS . A1819
SET ( A1819CCUST , A1819TACC , A1819NATU , A1819DESCR , A1819CLIEN ,
A1819DIREC , A1819TIPO , A1819MODO , A1819CIA , A1819UNID , A1819CECO ,
A1819UBI , A1819CTA , A1819SCTA , A1819EQUI , A1819ICIA , A1819FINI ,
A1819FFIN , A1819REGVI , A1819FREVI , A1819HREVI )
= ( IN_A1819CCUST ,
IN_A1819TACC ,
IN_A1819NATU ,
IN_A1819DESCR ,
IN_A1819CLIEN ,
IN_A1819DIREC ,
IN_A1819TIPO ,
IN_A1819MODO ,
IN_A1819CIA ,
IN_A1819UNID ,
IN_A1819CECO ,
IN_A1819UBI ,
IN_A1819CTA ,
IN_A1819SCTA ,
IN_A1819EQUI ,
IN_A1819ICIA ,
IN_A1819FINI ,
IN_A1819FFIN ,
IN_USR ,
IN_FEC ,
IN_HOR )
WHERE A1819CCUST = IN_A1819CCUST AND
A1819TACC = IN_A1819TACC_OLD ;
SET VL_MESSAGE = 'RECORD UPDATED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'D' THEN
DELETE FROM PRAXIS . A1819
WHERE A1819CCUST = IN_A1819CCUST AND
A1819TACC = IN_A1819TACC_OLD ;
SET VL_MESSAGE = 'RECORD REMOVED' ;
OPEN CURQRY ;
END IF ;


IF ( VL_SQLCODE <> 0 ) THEN		
	SELECT DB_MESSAGE INTO VL_MESSAGE FROM PRAXIS . INF054
WHERE DB_SQLCODE = VL_SQLCODE ;
	IF VL_MESSAGE IS NULL THEN
		SET VL_MESSAGE = 'AN UNEXPECTED ERROR OCCURRED, CODE '
CONCAT VL_SQLCODE ;
	END IF ;
ELSE
	SET VL_MESSAGE = 'OPERATION WAS SUCCESSFUL' ;			
END IF ;


OPEN CURQRY ;

END