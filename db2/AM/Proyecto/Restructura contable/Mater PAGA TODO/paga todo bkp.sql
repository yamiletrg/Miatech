CREATE PROCEDURE PRAXIS.PX170S02A1835 ( IN IN_ACTION CHAR(1),
                                        IN IN_A1835CCUST VARCHAR(3),
                                        IN IN_A1835FOPID VARCHAR(4),
                                        IN IN_A1835TARPT VARCHAR(19),
                                        IN IN_A1835CONC VARCHAR(40),
                                        IN IN_A1835CIA VARCHAR(2),
                                        IN IN_A1835UNIDA VARCHAR(2), -- READ ONLY
                                        --IN IN_A1835CENCO VARCHAR(6), 
                                        IN IN_A1835CENCO VARCHAR(7),  -- REESTRUCTURA CONTABLE
                                        IN IN_A1835UBICA VARCHAR(4),
                                       --  IN IN_A1835CUENT VARCHAR(4), 
                                         IN IN_A1835CUENT VARCHAR(6), -- REESTRUCTURA CONTABLE
                                        IN IN_A1835SUBCT VARCHAR(5),
                                        IN IN_A1835EQUI VARCHAR(4),
                                        IN IN_A1835INCIA VARCHAR(2),
                                        IN IN_USR VARCHAR(10),
                                        IN IN_FEC VARCHAR(8),
                                        IN IN_HOR VARCHAR(6),
                                        IN IN_A1835FOPID_OLD VARCHAR(4),
                                        IN IN_A1835TARPT_OLD VARCHAR(19),
                                        IN IN_A1835FINI VARCHAR(8),
                                        IN IN_A1835FFIN VARCHAR(8) )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.PX170S02A1835

BEGIN
DECLARE VL_SQLCODE INTEGER DEFAULT 0 ;
DECLARE SQLCODE INTEGER DEFAULT 0 ;
DECLARE VL_MESSAGE VARCHAR ( 100 ) DEFAULT NULL ;
DECLARE CURQRY CURSOR FOR SELECT VL_MESSAGE AS VMESSAGE , VL_SQLCODE AS VSQLCODE FROM ( VALUES ( '' , 0 ) ) AS TBL ;

SET VL_SQLCODE = REPLACE ( SQLCODE , '-' , '' ) ;

IF IN_ACTION = 'I' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1835
WHERE A1835CCUST = IN_A1835CCUST AND A1835FOPID = IN_A1835FOPID AND A1835TARPT = IN_A1835TARPT ) THEN

INSERT INTO PRAXIS . A1835
( A1835CCUST , A1835FOPID , A1835TARPT , A1835CONC , A1835CIA , A1835UNIDA , A1835CENCO , A1835UBICA , A1835CUENT , A1835SUBCT , A1835EQUI ,
A1835INCIA , A1835REGIS , A1835FREGI , A1835HREGI , A1835REGVI , A1835FREVI , A1835HREVI , A1835FINI , A1835FFIN )
VALUES ( IN_A1835CCUST ,
IN_A1835FOPID ,
IN_A1835TARPT ,
IN_A1835CONC ,
IN_A1835CIA ,
IN_A1835UNIDA ,
IN_A1835CENCO ,
IN_A1835UBICA ,
IN_A1835CUENT ,
IN_A1835SUBCT ,
IN_A1835EQUI ,
IN_A1835INCIA ,
IN_USR ,
IN_FEC ,
IN_HOR ,
'' ,
'' ,
'' ,
IN_A1835FINI ,
IN_A1835FFIN ) ;
SET VL_MESSAGE = 'RECORD INSERTED' ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
END IF ;
END IF ;

IF IN_ACTION = 'U' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1835
WHERE A1835CCUST = IN_A1835CCUST AND
( A1835FOPID = IN_A1835FOPID AND A1835TARPT = IN_A1835TARPT )

AND ( IN_A1835FOPID <> IN_A1835FOPID_OLD OR IN_A1835TARPT <> IN_A1835TARPT_OLD ) ) THEN

UPDATE PRAXIS . A1835
SET ( A1835CCUST , A1835FOPID , A1835TARPT , A1835CONC , A1835CIA , A1835UNIDA , A1835CENCO , A1835UBICA , A1835CUENT , A1835SUBCT , A1835EQUI ,
A1835INCIA , A1835REGVI , A1835FREVI , A1835HREVI , A1835FINI , A1835FFIN )
= ( IN_A1835CCUST ,
IN_A1835FOPID ,
IN_A1835TARPT ,
IN_A1835CONC ,
IN_A1835CIA ,
IN_A1835UNIDA ,
IN_A1835CENCO ,
IN_A1835UBICA ,
IN_A1835CUENT ,
IN_A1835SUBCT ,
IN_A1835EQUI ,
IN_A1835INCIA ,
IN_USR ,
IN_FEC ,
IN_HOR ,
IN_A1835FINI ,
IN_A1835FFIN )
WHERE A1835CCUST = IN_A1835CCUST AND
A1835FOPID = IN_A1835FOPID_OLD AND
A1835TARPT = IN_A1835TARPT_OLD ;
SET VL_MESSAGE = 'RECORD UPDATED' ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
END IF ;
END IF ;

IF IN_ACTION = 'D' THEN
DELETE FROM PRAXIS . A1835
WHERE A1835CCUST = IN_A1835CCUST AND
A1835FOPID = IN_A1835FOPID_OLD AND
A1835TARPT = IN_A1835TARPT_OLD ;
SET VL_MESSAGE = 'RECORD REMOVED' ;
END IF ;


IF ( VL_SQLCODE <> 0 ) THEN		
	SELECT DB_MESSAGE INTO VL_MESSAGE FROM PRAXIS . INF054 WHERE DB_SQLCODE = VL_SQLCODE ;
	IF VL_MESSAGE IS NULL THEN
		SET VL_MESSAGE = 'AN UNEXPECTED ERROR OCCURRED, CODE ' CONCAT VL_SQLCODE ;
	END IF ;
END IF ;


OPEN CURQRY ;

END