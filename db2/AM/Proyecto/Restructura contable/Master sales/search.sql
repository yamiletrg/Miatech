CREATE OR REPLACE PROCEDURE PRAXIS.SQP04480 ( IN IN_A1740TITRA VARCHAR(4),
                                   IN IN_A1740TIPO VARCHAR(1),
                                   IN IN_A1740SUBTI VARCHAR(4),
                                   IN IN_A1740CATEG VARCHAR(4),
                                   IN IN_A1740CTA VARCHAR(6),
                                   IN IN_A1740SCTA VARCHAR(5),
                                   INOUT IO_PAGNUM INTEGER,
                                   INOUT IO_PAGROW INTEGER,
                                   INOUT IO_TOTPAG INTEGER,
                                   INOUT IO_TOTROW INTEGER )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.SQP04480

BEGIN

DECLARE PAGROWINIT INT ;
DECLARE SQLPAG01 VARCHAR ( 1600 ) ;
DECLARE V_VCSQL VARCHAR ( 1500 ) ;
DECLARE V_ORDER VARCHAR ( 1500 ) DEFAULT 'A1740TITRA' ;
DECLARE CURQRY01 CURSOR FOR STMTQRY01 ;
	
SET V_VCSQL = 'SELECT COUNT(0) FROM (SELECT A1740TITRA,A1740TIPO,
    CASE WHEN A1740TIPO=''T'' THEN ''FARE''
     WHEN A1740TIPO=''C'' THEN ''COMISSION''
     WHEN A1740TIPO=''S'' THEN ''STAND ALONE''
     WHEN A1740TIPO=''O'' THEN ''CARGE''
     WHEN A1740TIPO=''A'' THEN ''ASSOCIATED''
     WHEN A1740TIPO=''F'' THEN ''AUDIT''
     WHEN A1740TIPO=''R'' THEN ''REVENUE''
     ELSE '''' END AS A1740TIPODESC,
A1740SUBTI,A1740CATEG,A1740CIA,A1740UNIDA,A1740CECOS,
A1740UBICA,A1740CTA,A1740SCTA,A1740EQUI,
A1740ICIA,A1740CLIE,A1740FINI,A1740FFIN,
A1740REGIS,A1740FREGI,A1740HREGI,A1740REGVI,A1740FREVI,A1740HREVI,
CASE WHEN A1740INTNU = ''Y'' THEN ''YES'' ELSE ''NO'' END AS A1740INTNU  
FROM PRAXIS.A1740 WHERE A1740TITRA NOT IN(''FLO'',''INT'',''TNU'') AND 
(A1740TITRA >= ''' CONCAT IN_A1740TITRA CONCAT ''' OR '''
CONCAT IN_A1740TITRA CONCAT ''' = '''') AND 
(A1740TIPO >= ''' CONCAT IN_A1740TIPO CONCAT ''' OR '''
CONCAT IN_A1740TIPO CONCAT ''' = '''') AND
(A1740SUBTI >= ''' CONCAT IN_A1740SUBTI CONCAT ''' OR '''
CONCAT IN_A1740SUBTI CONCAT ''' = '''') AND
(A1740CATEG >= ''' CONCAT IN_A1740CATEG CONCAT ''' OR '''
CONCAT IN_A1740CATEG CONCAT ''' = '''') AND
(A1740CTA >= ''' CONCAT IN_A1740CTA CONCAT ''' OR '''
CONCAT IN_A1740CTA CONCAT ''' = '''') AND
(A1740SCTA >= ''' CONCAT IN_A1740SCTA CONCAT ''' OR '''
CONCAT IN_A1740SCTA CONCAT ''' = '''')
) T ' ;

PREPARE STMTQRY01 FROM V_VCSQL ;
	OPEN CURQRY01 ;
		FETCH CURQRY01 INTO IO_TOTROW ;
	CLOSE CURQRY01 ;

SET V_VCSQL = ' SELECT ROW_NUMBER() OVER() AS NO, T.* FROM 
    (SELECT A1740TITRA,A1740TIPO,
    CASE WHEN A1740TIPO=''T'' THEN ''FARE''
     WHEN A1740TIPO=''C'' THEN ''COMISSION''
     WHEN A1740TIPO=''S'' THEN ''STAND ALONE''
     WHEN A1740TIPO=''O'' THEN ''CARGE''
     WHEN A1740TIPO=''A'' THEN ''ASSOCIATED''
     WHEN A1740TIPO=''F'' THEN ''AUDIT''
     WHEN A1740TIPO=''R'' THEN ''REVENUE''
     ELSE '''' END AS A1740TIPODESC,
     A1740SUBTI,A1740CATEG,A1740CIA,A1740UNIDA,A1740CECOS,
     A1740UBICA,A1740CTA,A1740SCTA,A1740EQUI,A1740ICIA,
    A1740CLIE,A1740FINI,A1740FFIN,A1740REGIS,A1740FREGI,A1740HREGI,
    A1740REGVI,A1740FREVI,A1740HREVI,
    CASE WHEN A1740INTNU = ''Y'' THEN ''YES'' ELSE ''NO'' END AS A1740INTNU 
FROM PRAXIS.A1740 WHERE A1740TITRA NOT IN(''FLO'',''INT'',''TNU'') AND
(A1740TITRA >= ''' CONCAT IN_A1740TITRA CONCAT ''' OR '''
CONCAT IN_A1740TITRA CONCAT ''' = '''') AND 
(A1740TIPO >= ''' CONCAT IN_A1740TIPO CONCAT ''' OR '''
CONCAT IN_A1740TIPO CONCAT ''' = '''') AND
(A1740SUBTI >= ''' CONCAT IN_A1740SUBTI CONCAT ''' OR '''
CONCAT IN_A1740SUBTI CONCAT ''' = '''') AND
(A1740CATEG >= ''' CONCAT IN_A1740CATEG CONCAT ''' OR '''
CONCAT IN_A1740CATEG CONCAT ''' = '''') AND
(A1740CTA >= ''' CONCAT IN_A1740CTA CONCAT ''' OR '''
CONCAT IN_A1740CTA CONCAT ''' = '''') AND
(A1740SCTA >= ''' CONCAT IN_A1740SCTA CONCAT ''' OR '''
CONCAT IN_A1740SCTA CONCAT ''' = '''')
) T' ;


IF IN_A1740TITRA <> '' THEN
SET V_ORDER = 'A1740TITRA' ;
END IF ;

IF IN_A1740TIPO <> '' THEN
SET V_ORDER = 'A1740TIPO' ;
END IF ;

IF IN_A1740SUBTI <> '' THEN
SET V_ORDER = 'A1740SUBTI' ;
END IF ;

IF IN_A1740CATEG <> '' THEN
SET V_ORDER = 'A1740CATEG' ;
END IF ;

IF IN_A1740CTA <> '' THEN
SET V_ORDER = 'A1740CTA' ;
END IF ;

IF IN_A1740SCTA <> '' THEN
SET V_ORDER = 'A1740SCTA' ;
END IF ;


SET SQLPAG01 = 'SELECT * FROM (' CONCAT V_VCSQL CONCAT ') AS RS 
WHERE RS.NO >= ' CONCAT IO_PAGNUM
CONCAT ' ORDER BY ' CONCAT V_ORDER ;
IF IO_PAGROW > 0 THEN
SET SQLPAG01 = SQLPAG01 CONCAT ' FETCH FIRST '
CONCAT IO_PAGROW CONCAT ' ROWS ONLY' ;
END IF ;

PREPARE STMTQRY01 FROM SQLPAG01 ;
OPEN CURQRY01 ;

END