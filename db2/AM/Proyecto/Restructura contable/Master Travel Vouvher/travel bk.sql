CREATE PROCEDURE PRAXIS.PX172S02A1838 ( IN IN_ACTION CHAR(1),
                                        IN IN_A1838CCUST CHAR(3),
                                        IN IN_A1838TIPO VARCHAR(4),
                                        IN IN_A1838AGENT VARCHAR(8),
                                        IN IN_A1838DESCR VARCHAR(45),
                                        IN IN_A1838CIA CHAR(2),
                                        IN IN_A1838UNIDA CHAR(2),
                                        --IN IN_A1838CENCO VARCHAR(6),
                                        IN IN_A1838CENCO VARCHAR(7), --REESTRUCTURA CONTABLE
                                        IN IN_A1838UBICA VARCHAR(4),
                                        -- IN IN_A1838CUENT VARCHAR(4),
                                        IN IN_A1838CUENT VARCHAR(6),
                                        IN IN_A1838SUBCT VARCHAR(5),
                                        IN IN_A1838EQUI VARCHAR(4),
                                        IN IN_A1838INCIA CHAR(2),
                                        IN IN_A1838FINI VARCHAR(8),
                                        IN IN_A1838FFIN VARCHAR(8),
                                        IN IN_USR VARCHAR(10),
                                        IN IN_FEC VARCHAR(8),
                                        IN IN_HOR VARCHAR(6),
                                        IN IN_A1838TIPO_OLD VARCHAR(4),
                                        IN IN_A1838AGENT_OLD VARCHAR(8) )
	RESULT SETS 1
	LANGUAGE SQL
	SPECIFIC PRAXIS.PX172S02A1838

BEGIN
DECLARE VL_SQLCODE INTEGER DEFAULT 0 ;
DECLARE SQLCODE INTEGER DEFAULT 0 ;
DECLARE VL_MESSAGE VARCHAR ( 100 ) DEFAULT NULL ;
DECLARE VL_USER_NAME VARCHAR ( 10 ) ;
DECLARE VL_FECHA VARCHAR ( 8 ) ;
DECLARE VL_HORA VARCHAR ( 10 ) ;

DECLARE CURQRY CURSOR FOR SELECT VL_MESSAGE AS VMESSAGE , VL_SQLCODE AS VSQLCODE FROM ( VALUES ( '' , 0 ) ) AS TBL ;
DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
SET VL_SQLCODE = REPLACE ( SQLCODE , '-' , '' ) ;

SET VL_USER_NAME = SESSION_USER ;
SET VL_FECHA = PRAXIS . FN_GET_CURRENTDAT ( ) ;
SET VL_HORA = CURRENT TIME ;
SET VL_HORA = REPLACE ( VL_HORA , ':' , '' ) ;

IF IN_ACTION = 'I' THEN
IF NOT EXISTS ( SELECT 0 FROM PRAXIS . A1838
WHERE A1838CCUST = IN_A1838CCUST AND A1838TIPO = IN_A1838TIPO AND A1838AGENT = IN_A1838AGENT ) THEN

INSERT INTO PRAXIS . A1838
(
A1838CCUST , A1838TIPO , A1838AGENT , A1838DESCR , A1838CIA ,
A1838UNIDA , A1838CENCO , A1838UBICA , A1838CUENT , A1838SUBCT , A1838EQUI ,
A1838INCIA , A1838FINI , A1838FFIN , A1838REGIS , A1838FREGI , A1838HREGI ,
A1838REGVI , A1838FREVI , A1838HREVI
)

VALUES
(
IN_A1838CCUST , IN_A1838TIPO , IN_A1838AGENT , IN_A1838DESCR , IN_A1838CIA ,
IN_A1838UNIDA , IN_A1838CENCO , IN_A1838UBICA , IN_A1838CUENT , IN_A1838SUBCT , IN_A1838EQUI ,
IN_A1838INCIA , IN_A1838FINI , IN_A1838FFIN , VL_USER_NAME , VL_FECHA , VL_HORA , '' , '' , ''
) ;

SET VL_MESSAGE = 'RECORD INSERTED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'U' THEN
IF NOT EXISTS (
SELECT 0 FROM PRAXIS . A1838
WHERE ( A1838CCUST = IN_A1838CCUST AND A1838TIPO = IN_A1838TIPO AND A1838AGENT = IN_A1838AGENT )
AND ( IN_A1838TIPO <> IN_A1838TIPO_OLD OR IN_A1838AGENT <> IN_A1838AGENT_OLD )
) THEN

UPDATE PRAXIS . A1838
SET
(
A1838CCUST , A1838TIPO , A1838AGENT , A1838DESCR , A1838CIA ,
A1838UNIDA , A1838CENCO , A1838UBICA , A1838CUENT , A1838SUBCT , A1838EQUI ,
A1838INCIA , A1838FINI , A1838FFIN , A1838REGVI , A1838FREVI , A1838HREVI
)

=
(
IN_A1838CCUST , IN_A1838TIPO , IN_A1838AGENT , IN_A1838DESCR , IN_A1838CIA ,
IN_A1838UNIDA , IN_A1838CENCO , IN_A1838UBICA , IN_A1838CUENT , IN_A1838SUBCT , IN_A1838EQUI ,
IN_A1838INCIA , IN_A1838FINI , IN_A1838FFIN , VL_USER_NAME , VL_FECHA , VL_HORA
)
WHERE A1838CCUST = IN_A1838CCUST
AND A1838TIPO = IN_A1838TIPO_OLD AND A1838AGENT = IN_A1838AGENT_OLD ;

SET VL_MESSAGE = 'RECORD UPDATED' ;
OPEN CURQRY ;
ELSE
SET VL_MESSAGE = 'RECORD EXISTS' ;
OPEN CURQRY ;
END IF ;
END IF ;

IF IN_ACTION = 'D' THEN
DELETE FROM PRAXIS . A1838
WHERE A1838CCUST = IN_A1838CCUST
AND A1838TIPO = IN_A1838TIPO_OLD AND A1838AGENT = IN_A1838AGENT_OLD ;

SET VL_MESSAGE = 'RECORD REMOVED' ;
OPEN CURQRY ;
END IF ;


IF ( VL_SQLCODE <> 0 ) THEN		
	SELECT DB_MESSAGE INTO VL_MESSAGE FROM PRAXIS . INF054 WHERE DB_SQLCODE = VL_SQLCODE ;
	IF VL_MESSAGE IS NULL THEN
		SET VL_MESSAGE = 'AN UNEXPECTED ERROR OCCURRED, CODE ' CONCAT VL_SQLCODE ;
	END IF ;
ELSE
	SET VL_MESSAGE = 'OPERATION WAS SUCCESSFUL' ;			
END IF ;


OPEN CURQRY ;

END