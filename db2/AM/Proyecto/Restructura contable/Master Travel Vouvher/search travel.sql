CREATE OR REPLACE PROCEDURE PRAXIS.PX172S01A1838 ( IN IN_A1838CCUST CHAR(3),
                                        IN IN_A1838TIPO CHAR(4),
                                        IN IN_A1838AGENT CHAR(8),
                                        IN IN_A1838CUENT VARCHAR(6),
                                        IN IN_A1838SUBCT VARCHAR(5),
                                        INOUT IO_PAGNUM INTEGER,
                                        INOUT IO_PAGROW INTEGER,
                                        INOUT IO_TOTPAG INTEGER,
                                        INOUT IO_TOTROW INTEGER )
	RESULT SETS 2
	LANGUAGE SQL
	SPECIFIC PRAXIS.PX172S01A1838

BEGIN

DECLARE CURQRY_COUNT CURSOR FOR

SELECT COUNT ( 0 ) FROM
(
SELECT * FROM PRAXIS . A1838
WHERE A1838CCUST = IN_A1838CCUST
AND ( A1838TIPO = IN_A1838TIPO OR IN_A1838TIPO = '' )
AND ( A1838AGENT = IN_A1838AGENT OR IN_A1838AGENT = '' )
AND ( A1838CUENT = IN_A1838CUENT OR IN_A1838CUENT = '' )
AND ( A1838SUBCT = IN_A1838SUBCT OR IN_A1838SUBCT = '' )
) AS T ;

DECLARE CURQRY01 CURSOR FOR
SELECT * FROM (
SELECT ROW_NUMBER ( ) OVER ( ) AS RN , T . * FROM
(
SELECT A1838CCUST , A1838TIPO , A1838AGENT , A1838DESCR , A1838CIA ,
A1838UNIDA , A1838CENCO , A1838UBICA , A1838CUENT , A1838SUBCT , A1838EQUI ,
A1838INCIA , A1838FINI , A1838FFIN , A1838REGIS , A1838FREGI , A1838HREGI ,
A1838REGVI , A1838FREVI , A1838HREVI
FROM PRAXIS . A1838
WHERE A1838CCUST = IN_A1838CCUST
AND ( A1838TIPO = IN_A1838TIPO OR IN_A1838TIPO = '' )
AND ( A1838AGENT = IN_A1838AGENT OR IN_A1838AGENT = '' )
AND ( A1838CUENT = IN_A1838CUENT OR IN_A1838CUENT = '' )
AND ( A1838SUBCT = IN_A1838SUBCT OR IN_A1838SUBCT = '' )
) AS T
) AS RS
WHERE RS . RN >= IO_PAGNUM
AND ( ( IO_PAGNUM - RS . RN + IO_PAGROW ) > 0 OR IO_PAGROW = - 1 ) ;

OPEN CURQRY01 ;
OPEN CURQRY_COUNT ;

FETCH CURQRY_COUNT INTO IO_TOTROW ;

END