CREATE OR REPLACE PROCEDURE PXFARES.SQP05727 
(
    IN VL_CCUST  VARCHAR(3), 
    IN VL_FECINI VARCHAR(8), 
    IN VL_FECFIN VARCHAR(8), 
    IN VL_OPCION VARCHAR(2)
)
    RESULT SETS 1
    LANGUAGE SQL
    SPECIFIC PXFARES.SQP05727
BEGIN

-- ===================================================
-- Cursor 1: CargoCP.py - Opción 1
-- ===================================================
DECLARE C1 CURSOR FOR
WITH FILTRAR_TICKET AS (
      SELECT A1672CCUST,A1672CIA, A1672FORMA, A1672SERIE, A1672SEQ, A1672FUENT, A1672CANAL, 
             A1672ITIN, A1672FVENT, A1672TIPOF, A1672PNRSP, A1672PAIVT, A1672CTYEM
      FROM PXSAUDIT.A1672 
      WHERE A1672CCUST = VL_CCUST 
        AND A1672FPROC BETWEEN VL_FECINI AND VL_FECFIN 
        AND A1672TRNCU = 'EXCH' 
        AND A1672STS0 <> '0'
),
FILTRO_A1673 AS (
      SELECT A1673CCUST, A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673MORIG, A1673TXORI, A1673CDTAX
      FROM PXSAUDIT.A1673 A1673
      WHERE A1673CCUST = VL_CCUST
        AND EXISTS (
          SELECT 1 
          FROM FILTRAR_TICKET FT 
          WHERE FT.A1672CCUST = A1673.A1673CCUST
            AND FT.A1672CIA   = A1673.A1673CIA 
            AND FT.A1672FORMA = A1673.A1673FORMA 
            AND FT.A1672SERIE = A1673.A1673SERIE 
            AND FT.A1672SEQ   = A1673.A1673SEQ
        )
        AND ( (LENGTH(TRIM(A1673CDTAX)) = 3 AND A1673CDTAX NOT IN ('F11','F31','F71','F72')) 
               OR A1673CDTAX = 'CP')
),
MORIGS AS (
      SELECT A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673MORIG,
             ROW_NUMBER() OVER (PARTITION BY A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ ORDER BY A1673MORIG) AS rn_morig
      FROM FILTRO_A1673
),
TXS AS (
      SELECT A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ, A1673TXORI, A1673CDTAX,
             ROW_NUMBER() OVER (PARTITION BY A1673CCUST,A1673CIA, A1673FORMA, A1673SERIE, A1673SEQ ORDER BY A1673TXORI, A1673CDTAX) AS rn_tx
      FROM FILTRO_A1673
)
SELECT 
      FT.A1672CCUST,
      FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE AS TICKET,
      FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,FT.A1672CTYEM,
      FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP,
      CASE WHEN MAX(CASE WHEN M.rn_morig = 1 THEN M.A1673MORIG END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 1 THEN M.A1673MORIG END))) END AS MORIG_1,
      CASE WHEN MAX(CASE WHEN M.rn_morig = 2 THEN M.A1673MORIG END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 2 THEN M.A1673MORIG END))) END AS MORIG_2,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673TXORI END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673TXORI END))) END AS TXORI_1,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673CDTAX END) IS NULL THEN '' ELSE TRIM(MAX(CASE WHEN TX.rn_tx = 1 THEN TX.A1673CDTAX END)) END AS CDTAX_1,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673TXORI END) IS NULL THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673TXORI END))) END AS TXORI_2,
      CASE WHEN MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673CDTAX END) IS NULL THEN '' ELSE TRIM(MAX(CASE WHEN TX.rn_tx = 2 THEN TX.A1673CDTAX END)) END AS CDTAX_2
FROM FILTRAR_TICKET FT
LEFT JOIN MORIGS M 
       ON FT.A1672CCUST = M.A1673CCUST
      AND FT.A1672CIA   = M.A1673CIA 
      AND FT.A1672FORMA = M.A1673FORMA 
      AND FT.A1672SERIE = M.A1673SERIE 
      AND FT.A1672SEQ   = M.A1673SEQ
LEFT JOIN TXS TX 
       ON FT.A1672CCUST = TX.A1673CCUST
      AND FT.A1672CIA   = TX.A1673CIA 
      AND FT.A1672FORMA = TX.A1673FORMA 
      AND FT.A1672SERIE = TX.A1673SERIE 
      AND FT.A1672SEQ   = TX.A1673SEQ
GROUP BY FT.A1672CCUST,FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE,
         FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,
         FT.A1672CTYEM,FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP;

-- ===================================================
-- Cursor 2: versión A1532 (equivalente a CargoCP_NEW.py Opción 2)
-- ===================================================
DECLARE C2 CURSOR FOR
WITH FILTRAR_TICKET AS(
	SELECT A1672CCUST,A1672CIA, A1672FORMA, A1672SERIE, A1672SEQ, A1672FUENT, A1672CANAL, 
           A1672ITIN, A1672FVENT, A1672TIPOF, A1672PNRSP, A1672PAIVT, A1672CTYEM
      FROM PXSAUDIT.A1672 
      WHERE A1672CCUST = VL_CCUST 
        AND A1672FPROC BETWEEN VL_FECINI AND VL_FECFIN 
        AND A1672TRNCU = 'EXCH' 
        AND A1672STS0 <> '0'
),
FILTRO_A1532 AS (
    	SELECT A1532CCUST, A1532CIA,A1532FORMA,A1532SERIE,A1532SEQ,A1532CTAX,A1532MTAX,A1532VTAX
    	FROM PRAXIS.A1532 A1532
    	WHERE A1532CCUST = VL_CCUST
    	  AND EXISTS (
    		SELECT 1 
    		FROM FILTRAR_TICKET FT
    		WHERE FT.A1672CCUST = A1532.A1532CCUST
    		  AND FT.A1672CIA   = A1532.A1532CIA
    		  AND FT.A1672FORMA = A1532.A1532FORMA
    		  AND FT.A1672SERIE = A1532.A1532SERIE
    		  AND FT.A1672SEQ   = A1532.A1532SEQ
    	  )
    	  AND ( (LENGTH(TRIM(A1532CTAX))= 3 AND A1532CTAX NOT IN('F11', 'F31', 'F71', 'F72')) 
                 OR A1532CTAX ='CP')
),
MORIGS AS (
	    SELECT A1532CCUST,A1532CIA,A1532FORMA,A1532SERIE,A1532SEQ,A1532MTAX,
	           ROW_NUMBER() OVER (ORDER BY A1532MTAX) AS rn_morig
	    FROM FILTRO_A1532
),
TXS_SUM AS (
    	SELECT A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ, A1532CTAX, A1532VTAX,
               SUM(CASE WHEN A1532CTAX = 'IVA' THEN A1532VTAX ELSE 0 END) AS TXORI_1,
               SUM(CASE WHEN A1532CTAX = 'CP'  THEN A1532VTAX ELSE 0 END) AS TXORI_2
	    FROM FILTRO_A1532
	    GROUP BY A1532CCUST, A1532CIA, A1532FORMA, A1532SERIE, A1532SEQ, A1532CTAX, A1532VTAX
)
SELECT 
    FT.A1672CCUST,
    FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE AS TICKET,
    FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,FT.A1672CTYEM,
    FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP,	
    CASE WHEN MAX(CASE WHEN M.rn_morig = 1 THEN M.A1532MTAX END) IS NULL 
         THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 1 THEN M.A1532MTAX END))) END AS MORIG_1,
	CASE WHEN MAX(CASE WHEN M.rn_morig = 2 THEN M.A1532MTAX END) IS NULL 
	     THEN '' ELSE TRIM(CHAR(MAX(CASE WHEN M.rn_morig = 2 THEN M.A1532MTAX END))) END AS MORIG_2,
	SUM(CASE WHEN TX.A1532CTAX = 'IVA' THEN TX.A1532VTAX ELSE 0 END) AS TXORI_1,
    CASE WHEN SUM(CASE WHEN TX.A1532CTAX = 'IVA' THEN TX.A1532VTAX ELSE 0 END) > 0 THEN 'IVA' END AS CDTAX_1,
    SUM(CASE WHEN TX.A1532CTAX = 'CP' THEN TX.A1532VTAX ELSE 0 END) AS TXORI_2,
    CASE WHEN SUM(CASE WHEN TX.A1532CTAX = 'CP' THEN TX.A1532VTAX ELSE 0 END) > 0 THEN 'CP' END AS CDTAX_2

FROM FILTRAR_TICKET FT
LEFT JOIN MORIGS M 
       ON FT.A1672CCUST = M.A1532CCUST
      AND FT.A1672CIA   = M.A1532CIA 
      AND FT.A1672FORMA = M.A1532FORMA 
      AND FT.A1672SERIE = M.A1532SERIE 
      AND FT.A1672SEQ   = M.A1532SEQ
LEFT JOIN TXS_SUM TX 
       ON FT.A1672CCUST = TX.A1532CCUST
      AND FT.A1672CIA   = TX.A1532CIA
      AND FT.A1672FORMA = TX.A1532FORMA
      AND FT.A1672SERIE = TX.A1532SERIE
      AND FT.A1672SEQ   = TX.A1532SEQ
GROUP BY FT.A1672CCUST,FT.A1672CIA||FT.A1672FORMA||FT.A1672SERIE,
         FT.A1672SEQ,FT.A1672FUENT,FT.A1672CANAL,FT.A1672PAIVT,
         FT.A1672CTYEM,FT.A1672ITIN,FT.A1672FVENT,FT.A1672TIPOF,FT.A1672PNRSP;

-- ===================================================
-- Opciones de ejecución
-- ===================================================
IF VL_OPCION = '01' THEN
    OPEN C1;
ELSEIF VL_OPCION = '02' THEN
    OPEN C2;
ELSEIF VL_OPCION = '03' THEN
    -- Para futuras opciones
    BEGIN
        -- vacío
    END;
END IF;

END 
